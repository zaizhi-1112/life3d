"""Curated form descriptions for world sculptures. Only shape is sent to Aholo."""
from dataclasses import dataclass, field, replace

from moment_shapes import DROP, EXISTING, EXTRA


@dataclass(frozen=True)
class Sculpture:
    id: str
    title: str
    description: str
    zone: str
    slot: int
    shape: str
    era: str = ""
    tuning: dict = field(default_factory=dict)

    @property
    def prompt(self):
        color = COLORS.get(self.id.removesuffix("-paint"), "主体用灰绿和雾蓝分色，木构件暖棕，凸起小配件陶土红")
        return (self.shape + "。" + color + "。低饱和手绘彩色陶瓷微缩模型，暖木色、陶土红、"
                "灰绿、雾蓝、奶油白为主，分区施釉，保留清晰的固有色差，哑光，柔和边缘。"
                "单件独立，正面偏右四分之三视角，完整入画，中性浅灰背景，无布景、文字、标志、人物或人手。")

    @property
    def placement(self):
        value = {"zone": self.zone, "slot": self.slot}
        if self.era:
            value["era"] = self.era
        value.update(self.tuning)
        return value


